const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
test('deployment adds policies without writing or changing existing CMS records',async()=>{
 const signaturePromotions=JSON.parse(fs.readFileSync("fixtures/tutimi-signature-promotions.json"));
 const policies=JSON.parse(fs.readFileSync('netlify/functions/after-sales.json'));
 const existing={items:[{id:'old',content:'Latest text',archivedAt:'2026-01-01',unknown:{keep:true}}, {...policies.items[0],archivedAt:'2026-11-09'}],updatedAt:'unchanged'};
 let writes=0;
 let code=fs.readFileSync('netlify/functions/data.mjs','utf8').replace(/^import .*;\n/gm,'').replace('export default async','handler = async').replace(/export const config.*;/,'');
 const context=vm.createContext({policies,signaturePromotions,seed:{items:[]},getStore:()=>({get:async()=>structuredClone(existing),setJSON:async()=>writes++}),Response});
 vm.runInContext(code,context);
 const response=await context.handler({method:'GET'});
 const data=await response.json();
 assert.equal(writes,0); assert.equal(data.updatedAt,existing.updatedAt);
 assert.deepEqual(data.items.slice(0,2),existing.items);
 assert.equal(data.items.length,28);
 assert.equal(new Set(data.items.map(x=>x.id)).size,28);
 assert.ok(policies.items.every(x=>x.policy.status==='active'&&x.policy.effectiveDate==='2026-11-10'));
});
